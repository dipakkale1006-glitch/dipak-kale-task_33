'use strict';

const mongoose = require('mongoose');

const PRIORITIES = ['low', 'medium', 'high'];

/**
 * Task schema - the single resource this API exposes.
 *
 * Note the deliberate split between `title` and `description`, and the small set
 * of optional fields that keep the model useful without turning it into a
 * project-management tool.
 */
const taskSchema = new mongoose.Schema(
  {
    title: {
      type: String,
      required: [true, 'Title is required'],
      trim: true,
      minlength: [2, 'Title must be at least 2 characters'],
      maxlength: [160, 'Title cannot exceed 160 characters'],
    },
    description: {
      type: String,
      trim: true,
      default: '',
      maxlength: [1000, 'Description cannot exceed 1000 characters'],
    },
    completed: {
      type: Boolean,
      default: false,
    },
    priority: {
      type: String,
      enum: {
        values: PRIORITIES,
        message: 'Priority must be one of: low, medium, high',
      },
      default: 'medium',
    },
    category: {
      type: String,
      trim: true,
      default: 'general',
      maxlength: [60, 'Category cannot exceed 60 characters'],
    },
    dueDate: {
      type: Date,
      default: null,
    },
  },
  {
    // `timestamps` gives createdAt/updatedAt for free, which is exactly the
    // "unique identifier + timestamps generated by the server" behaviour
    // planned in the design document.
    timestamps: true,
    versionKey: false,
    toJSON: { virtuals: true },
    toObject: { virtuals: true },
  },
);

// ---------------------------------------------------------------------------
// Indexes
// ---------------------------------------------------------------------------
// The list endpoint sorts by newest first, and the home screen filters on
// `completed` while showing pending items first. These compound indexes keep
// those two hot paths from doing a full collection scan.
taskSchema.index({ createdAt: -1 });
taskSchema.index({ completed: 1, createdAt: -1 });

// Text index powering the `search` query parameter.
taskSchema.index({ title: 'text', description: 'text' });

// ---------------------------------------------------------------------------
// Virtuals
// ---------------------------------------------------------------------------

/** True when a due date exists and is already in the past while not completed. */
taskSchema.virtual('isOverdue').get(function isOverdue() {
  if (!this.dueDate || this.completed) return false;
  return new Date(this.dueDate).getTime() < Date.now();
});

/** Exposes the schema's enum to the rest of the app without duplicating it. */
taskSchema.statics.PRIORITIES = PRIORITIES;

const Task = mongoose.model('Task', taskSchema);

module.exports = Task;
module.exports.PRIORITIES = PRIORITIES;
